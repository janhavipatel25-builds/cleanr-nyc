  hydro: ['....#....', '...###...', '..#####..', '.#######.', '.#######.', '.#######.', '..#####..'],
  wind: ['....#....', '....#....', '....#....', '..##.##..', '.#..#..#.', '....#....', '...###...'],
  otherRenewables: ['......##.', '....####.', '..######.', '.#####.#.', '.###.##..', '.#.##....', '#........'],
  gas: ['....#....', '...##....', '..###....', '..####...', '.######..', '.###.##..', '..#####..'],
  laundry: ['#########', '#.#.#...#', '#########', '#..###..#', '#.#...#.#', '#.#...#.#', '#..###..#', '#########'],
  dish: ['#########', '#########', '#.......#', '#.#.#.#.#', '#.#.#.#.#', '#.......#', '#########'],
